#!/usr/bin/env node
/**
 * PUBLIC_INTERFACE
 * Ensure that node_modules/entities/lib/decode.js exists for consumers that require it,
 * such as @vue/compiler-core's CJS bundle. This script runs before build.
 *
 * Robust strategy:
 * - Always write a tiny adapter at node_modules/entities/lib/decode.js that proxies decode functions
 *   from entities/lib/index.js (which is present in v4.x). This avoids depending on ESM files that
 *   may reference non-published generated assets.
 */
const fs = require('fs');
const path = require('path');

const projectRoot = process.cwd();
const libDir = path.join(projectRoot, 'node_modules', 'entities', 'lib');
const decodeCjs = path.join(libDir, 'decode.js');

function ensureDir(p) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
}

function writeStableAdapter() {
  const adapter = `"use strict";
/**
 * Adapter generated by scripts/ensure-entities-decode.cjs
 * Provides decode functions by importing from entities/lib/esm/decode.js exclusively
 * and re-exporting via CommonJS for @vue/compiler-core CJS consumers.
 * This avoids requiring entities/lib/index.js which references ./generated/* in encode.js.
 */
let esmDecode;
try {
  esmDecode = require("./esm/decode.js");
} catch (_e) {
  // As a last resort, define minimal safe stubs to prevent hard failure.
  esmDecode = {
    EntityDecoder: class {},
    DecodingMode: { Legacy: 0, Strict: 1 },
    decodeXML: (s) => String(s ?? ""),
    decodeHTML: (s) => String(s ?? ""),
    decodeHTMLStrict: (s) => String(s ?? ""),
    decodeHTMLAttribute: (s) => String(s ?? ""),
  };
}
module.exports = {
  EntityDecoder: esmDecode.EntityDecoder,
  DecodingMode: esmDecode.DecodingMode,
  decodeXML: esmDecode.decodeXML,
  decodeHTML: esmDecode.decodeHTML,
  decodeHTMLStrict: esmDecode.decodeHTMLStrict,
  decodeHTMLAttribute: esmDecode.decodeHTMLAttribute,
};
`;
  ensureDir(decodeCjs);
  fs.writeFileSync(decodeCjs, adapter, 'utf8');
  console.log('[ensure-entities-decode] Ensured adapter at entities/lib/decode.js');
}

(function main() {
  try {
    writeStableAdapter();
  } catch (err) {
    console.error('[ensure-entities-decode] Error:', err && err.message ? err.message : err);
    // Non-fatal: do not block the build but log error for visibility.
  }
})();
